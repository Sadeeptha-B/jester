import { chase, emote, flash, fx, gather, go, say, wait, type Beat, type EventDef } from '../schema';

const any = (...not: string[]) => ({ any: true as const, not: not.length ? not : undefined });

function scene(id: string, at: string, cast: EventDef['cast'], beats: Beat[], extra: Partial<EventDef> = {}): EventDef {
  return { id, kind: 'ambient', weight: 1, tags: [id.split('_')[0]], cast, at, beats, effects: [], cooldownDays: 3, ...extra };
}

